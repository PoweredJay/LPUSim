#!/usr/bin/env python3
"""Write results/REPORT.md: every number the README reports, computed from the files a run wrote.

    python3 scripts/report.py [--results results] [--planning planning]

Nothing here is typed in by hand. If an input file is missing the script fails, so a stale or
partial results/ directory cannot produce a report.
"""
import argparse
import json
import os
import statistics
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from plots import load_paper, load_roofline, pair_with_paper, read_csv  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PEAK = 4 * 2 * 320 * 320 / 1000.0   # TOPS at 1 GHz, 4 planes
TILES, HEMIS, LW_CYCLES = 16, 2, 20  # roofline workload: 16 weight tiles; LW = 20 issues per tile


def summary(results, name):
    with open(os.path.join(results, name)) as f:
        return json.load(f)


def fit(points, low_max=32, high_min=256):
    """cycles = a + M for small M (weight-delivery bound), cycles = b + 4M for large M (MXM bound)."""
    a = statistics.median(c - m for m, _, c, _, _ in points if m <= low_max)
    b = statistics.median(c - 4 * m for m, _, c, _, _ in points if m >= high_min)
    return a, b


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(ROOT, "results"))
    ap.add_argument("--planning", default=os.path.join(ROOT, "planning"))
    a = ap.parse_args()
    R = a.results
    L = []
    w = L.append

    # ---------------------------------------------------------------- tests
    with open(os.path.join(R, "tests.log")) as f:
        tlog = f.read()
    passed, failed = tlog.count("[PASS]"), tlog.count("[FAIL]")

    # ---------------------------------------------------------------- ResNet
    nets = {d: summary(R, f"resnet{d}_summary.json") for d in (50, 101, 152)}
    sens = {k: summary(os.path.join(R, "sensitivity"), f"resnet50_{k}_summary.json")
            for k in ("mem1", "sxm14", "nooverlap")}
    base = nets[50]["cycles"]

    w("# Results report")
    w("")
    w("Generated by `make` (scripts/reproduce.sh -> scripts/report.py) from the files in `results/`.")
    w("Do not edit by hand. Batch 1, host I/O excluded, Sync preamble and superlane stagger included.")
    w("")
    w(f"Tests: {passed} passed, {failed} failed (`results/tests.log`).")
    w("")
    w("## ResNet")
    w("")
    w("| model | cycles | IPS @ 0.9 GHz | latency @ 0.9 GHz | IPS @ 1 GHz | paper IPS | check |")
    w("|---|---:|---:|---:|---:|---:|---|")
    for d, s in nets.items():
        if s["timing_only_projection"]:
            check = (f"timing-only projection ({s['weight_tiles_aliased']} of {s['weight_tiles']} weight tiles aliased), "
                     f"{s['violations']} violations")
        else:
            check = (("bit-exact" if s["golden_checked"] and s["logits_wrong"] == 0 else
                      f"MISMATCH: {s['logits_wrong']} logits differ") +
                     f", {s['violations']} violations, {s['iq_underflows']} IQ underflows")
        w(f"| ResNet-{d} | {s['cycles']:,} | {s['ips_0.9GHz']:,.0f} | {s['latency_us_0.9GHz']:.1f} us | "
          f"{s['ips_1GHz']:,.0f} | {s['paper_ips']:,} | {check} |")
    w("")
    s = nets[50]
    w(f"ResNet-50 Ifetch: {s['ifetches']} refills ({s['ifetch_vectors']} text vectors) on {s['iqs_fetching']} of "
      f"{s['iqs_used']} IQs with code; {s['fetched_bytes'] / 1000:.1f} KB of {s['text_bytes'] / 1000:.1f} KB of text "
      f"fetched from {s['text_words']} MEM words ({s['ifetch_read_port_cycles']} read-port cycles); "
      f"{s['iq_underflows']} underflows, {s['iq_overflows']} overflows, max IQ fill {s['iq_max_fill']} B of 640; "
      f"{s['iq_entries']:,} IQ entries on {s['iqs_used']} of {s['iqs_total']} IQs.")
    w("")
    w("Refills on ResNet-101 / 152: " + " / ".join(
        f"{nets[d]['ifetches']} ({nets[d]['iq_underflows']} underflows, {nets[d]['iq_overflows']} overflows)"
        for d in (101, 152)) + ".")
    w("")
    w("![ResNet throughput](figures/resnet_ips.png)")
    w("")
    w("## Sensitivity (ResNet-50)")
    w("")
    w("| run | flag | cycles | vs baseline | check |")
    w("|---|---|---:|---:|---|")
    rows = [("baseline", "", nets[50]),
            ("MEM IQ single-issue (Read and Write serialize)", "--mem-single-issue", sens["mem1"]),
            ("SXM 14 hops wide per side instead of 4", "--sxm-hops 14", sens["sxm14"]),
            ("no layer overlap (each layer waits for the previous)", "--no-layer-overlap", sens["nooverlap"])]
    for name, flag, x in rows:
        ok = "bit-exact" if x["golden_checked"] and x["logits_wrong"] == 0 else f"{x['logits_wrong']} logits differ"
        w(f"| {name} | {f'`{flag}`' if flag else '(none)'} | {x['cycles']:,} | {100.0 * (x['cycles'] / base - 1):+.1f}% | "
          f"{ok}, {x['violations']} violations |")
    w("")

    # ---------------------------------------------------------------- roofline
    rl = load_roofline(os.path.join(R, "roofline.csv"))
    wide = load_roofline(os.path.join(R, "roofline_wide_weights.csv"))
    paper = load_paper(os.path.join(a.planning, "paper_fig9.csv"))
    names = list(rl)
    near = rl[names[0]]
    wname = list(wide)[0]
    allpts = [p for v in list(rl.values()) + list(wide.values()) for p in v]
    bad = [p for p in allpts if not p[4]]

    w("## Roofline ([M x 320] x [320 x 5120] int8, `results/roofline.csv`)")
    w("")
    w(f"Throughput is TOPS at 1 GHz (ops per cycle / 1000), the paper's Fig. 9 axis; at the 0.9 GHz nominal "
      f"clock multiply by 0.9. Peak = 4 planes x 2 x 320 x 320 = {PEAK:.1f} TOPS. Cycles run from the first "
      f"instruction to the last result write (no Sync preamble). {len(allpts)} simulated points, "
      f"{len(allpts) - len(bad)} bit-exact with 0 violations and 0 IQ underflows.")
    w("")
    ms = [p[0] for p in near]
    w("| M | ops/B | " + " | ".join(n for n in names) + f" | {wname} (experiment) |")
    w("|---:|---:|" + "---:|" * (len(names) + 1))
    for M in ms:
        cells = []
        for v in list(rl.values()) + [wide[wname]]:
            p = next((q for q in v if q[0] == M), None)
            cells.append(f"{p[3]:.1f} ({p[2]:,} cyc)" if p else "")
        w(f"| {M} | {2 * M:,} | " + " | ".join(cells) + " |")
    w("")
    fits = {n: fit(rl[n]) for n in names}
    a0, b0 = fits[names[0]]
    w("Piecewise fit (median residual), weights next to the MXM:")
    w(f"* M <= 32: cycles = {a0:.0f} + M. Weight-delivery bound: the 16 tiles are {TILES // HEMIS} per hemisphere, "
      f"both planes of a hemisphere load from the same 16 weight slices (one read port each), so a "
      f"hemisphere's {TILES // HEMIS} LWs run one after another: {TILES // HEMIS} x {LW_CYCLES} = "
      f"{TILES // HEMIS * LW_CYCLES} cycles. The other {a0 - TILES // HEMIS * LW_CYCLES:.0f} cycles are the lead-in "
      f"before the first LW and the tail after the last (its ABC, the trip to the VXM, the write).")
    w(f"* M >= 256: cycles = {b0:.0f} + 4M. MXM bound: 4 rounds of M vectors per plane, back to back.")
    w(f"* The two lines cross at M = {(a0 - b0) / 3:.1f} ({2 * (a0 - b0) / 3:.0f} ops/B).")
    for n in names[1:]:
        an, bn = fits[n]
        w(f"* {n}: +{an - a0:.0f} cycles at low load, +{bn - b0:.0f} at high load (longer weight path to the MXM).")
    w("")
    w("### Ours vs paper Fig. 9")
    w("")
    w("Paper values from `planning/paper_fig9.csv` (see its header for where they come from). A paper point is "
      "compared only where a simulated M has 2M within 1% of its x value.")
    w("")
    pn = pair_with_paper(near, paper)
    pw = {p[0]: p for p in pair_with_paper(wide[wname], paper)}
    w(f"| paper ops/B | paper TOPS | sim M | ours TOPS ({names[0]}) | ours vs paper | {wname} | vs paper |")
    w("|---:|---:|---:|---:|---:|---:|---:|")
    for px, pt, M, st, pct in pn:
        q = pw.get(px)
        w(f"| {px:,} | {pt:.0f} | {M} | {st:.1f} | {pct:+.1f}% | " +
          (f"{q[3]:.1f} | {q[4]:+.1f}% |" if q else " | |"))
    unpaired = [px for px, _ in paper if px not in {p[0] for p in pn}]
    if unpaired:
        w("")
        w("No simulated point for paper x = " + ", ".join(f"{x:,}" for x in unpaired) +
          " (M = 4096 needs a 4,096-word store in one bank; the largest store is 4,095 words).")
    w("")
    low = [p for p in pn if p[0] <= 16]
    mid = max(pn, key=lambda p: p[4])
    hi = [p for p in pn if p[0] >= 1000]
    wl = [pw[p[0]] for p in low if p[0] in pw]
    w("### Why ours is below the paper at low operational intensity and above it in the middle")
    w("")
    w(f"* **Low intensity ({', '.join(f'{p[4]:+.0f}% at {p[0]}' for p in low)} ops/B).** Below the crossover our "
      f"time is almost flat ({a0:.0f} + M cycles): it is set by loading weights, not by compute. Our lowering "
      f"[Ours] puts all weight tiles in 16 slices per hemisphere (MEM28-43), so the two planes of a hemisphere "
      f"share 16 read ports and take turns loading. The paper's hardware loads both at once: \"using all 32 "
      f"streams in each direction allows us to emplace weights in both MXM planes simultaneously on both MXM "
      f"hemispheres, loading all 409,600 weights on-chip in less than 40 cycles\" (ISCA 2020 p.152; the same "
      f"text is in patent US 11,822,510). Our layout needs 40 cycles plus transit for the same load. "
      f"Spreading the weights over 32 slices ({wname}), so the two planes' LWs can partly overlap, is the "
      f"experiment that tests this: it cuts the gap to "
      f"{', '.join(f'{q[4]:+.0f}% at {q[0]}' for q in wl)} ops/B and leaves high intensity unchanged. So most of "
      f"the low-intensity gap is our weight layout, not the hardware timing model. It does not close fully "
      f"because the two planes' loads still overlap only partly in that layout, and the pipeline tail of a "
      f"one-shot run (the last tile's ABC d_func 20 [I], the trip to the VXM, the write) is never hidden.")
    mw = pw.get(mid[0])
    w(f"* **Middle intensity (up to {mid[4]:+.0f}% at {mid[0]:,} ops/B).** Above the crossover our time is {b0:.0f} + 4M "
      f"cycles: the scheduler hides the next tile's LW completely behind the current ABC and leaves no bubble "
      f"between rounds, so our curve is max(weight-bound, MXM-bound) plus a fixed tail, with a sharp knee at "
      f"{2 * (a0 - b0) / 3:.0f} ops/B. The paper's curve bends gradually over the same range. We cannot see the "
      f"paper's schedule, so this is an inference: its compiled programs lose some cycles near the knee "
      f"(imperfect LW/ABC overlap, gaps between rounds) where ours lose none, which puts our overestimate just "
      f"past the knee. It is not the weight placement: the 32-slice experiment is "
      + (f"{mw[4]:+.0f}% at the same load. " if mw else "about the same there. ") +
      f"Our perfect overlap rests on assumed [A] latencies (LW 1 cycle per issue, IW 1 cycle) and the inferred "
      f"[I] ABC d_func of 20; longer real latencies would lower our curve most around the knee.")
    w(f"* **High intensity ({', '.join(f'{p[4]:+.0f}%' for p in hi)} from {hi[0][0]:,} ops/B up).** Both curves "
      f"approach the {PEAK:.0f} TOPS peak; only our {b0:.0f}-cycle fixed tail is left, so the gap shrinks.")
    w("")
    w("![roofline](figures/roofline.png)")
    w("")
    w("![ours vs paper](figures/roofline_vs_paper.png)")
    w("")

    # ---------------------------------------------------------------- latency sensitivity (tornado)
    sens_rows = read_csv(os.path.join(R, "latency_sensitivity.csv"))
    sbase = int(sens_rows[0]["baseline_cycles"])
    w("## Latency sensitivity (ResNet-50, `results/latency_sensitivity.csv`)")
    w("")
    w(f"Each assumed [A] value halved and doubled on its own (`scripts/sensitivity.py`); baseline {sbase:,} "
      "cycles. Every run is bit-exact with 0 violations. Latencies are whole cycles, so a 1-cycle value has no "
      "halved run.")
    w("")
    w("| value | tag | assumed | halved | doubled | range |")
    w("|---|---|---:|---:|---:|---:|")
    for r in sens_rows:
        unit = " hops" if r["unit"] == "hops" else ""
        def delta(c):
            if not c:
                return "n/a"
            d = int(c) - sbase
            return f"{d:+,} ({100.0 * d / sbase:+.2f}%)"
        w(f"| {r['instruction']} | {r['tag']} | {r['assumed']}{unit} | {delta(r['half_cycles'])} | "
          f"{delta(r['double_cycles'])} | {int(r['swing_cycles']):,} |")
    inst = [r for r in sens_rows if r["unit"] != "hops"]
    worst_inst = max(inst, key=lambda r: max(abs(int(c) - sbase) for c in (r["half_cycles"], r["double_cycles"]) if c))
    wi = max(abs(int(c) - sbase) for c in (worst_inst["half_cycles"], worst_inst["double_cycles"]) if c)
    w("")
    w(f"No instruction latency moves ResNet-50 by more than {100.0 * wi / sbase:.1f}% ({worst_inst['instruction']}, "
      f"{wi:+,} cycles); the SXM width, a floorplan distance, matters most. This sweep is ResNet-50 only: it does "
      "not test the roofline's middle-intensity gap.")
    w("")
    w("![latency sensitivity](figures/latency_sensitivity.png)")
    w("")
    out = os.path.join(R, "REPORT.md")
    with open(out, "w") as f:
        f.write("\n".join(L))
    print(f"wrote {os.path.relpath(out, ROOT)}")
    if failed or bad or any(nets[d]["violations"] for d in nets) or nets[50]["logits_wrong"]:
        print("report: some check failed (see REPORT.md)", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
